namespace Lib.MathCore.Utilities;

/// Клас для допоміжних операцій з оцінками (scores) нейронної мережі.
public static class ScoreUtilities
{
    /// Знаходить індекс елемента з найбільшим значенням у масиві.
    /// В контексті GPT це означає вибір найбільш ймовірного наступного токена.
    public static int GetArgMax(ReadOnlySpan<double> scores)
    {
        // ПЕРЕВІРКА НА ПОРОЖНІЙ МАСИВ:
        // Якщо масив не містить даних (довжина 0), ми повертаємо -1.
        // Це запобігає вильоту програми при спробі звернутися до неіснуючих елементів.
        if (scores.Length == 0) 
        {
            return -1;
        }

        // ІНІЦІАЛІЗАЦІЯ:
        // Ми припускаємо, що перший елемент (індекс 0) і є найбільшим.
        // Далі ми будемо порівнювати всіх інших з цим "лідером".
        int maxIndex = 0;
        
        // ЦИКЛ ПО МАСИВУ:
        // Починаємо з i = 1, оскільки елемент під індексом 0 ми вже врахували вище.
        // Цикл працює доти, доки i менше за загальну кількість елементів (scores.Length).
        for (int i = 1; i < scores.Length; i++)
        {
            // ПОРІВНЯННЯ ЗНАЧЕНЬ:
            // scores[i] — це значення поточного елемента, який ми перевіряємо.
            // scores[maxIndex] — це значення нашого поточного "чемпіона" (максимуму).
            if (scores[i] > scores[maxIndex])
            {
                // ОНОВЛЕННЯ ЛІДЕРА:
                // Якщо поточний елемент виявився більшим за попередній максимум,
                // ми запам'ятовуємо його номер (індекс i) як новий maxIndex.
                maxIndex = i;
            }
        }

        // РЕЗУЛЬТАТ:
        // Після того, як ми перевірили весь масив, повертаємо індекс того самого
        // "найвагомішого" слова, яке модель вважає найбільш доречним.
        return maxIndex;
    }
}